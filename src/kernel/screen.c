void clear_screen(uint32_t color)
{
	volatile uint8_t* fb = (volatile uint8_t*)VBE->fb_phys_addr;
	uint32_t total_pixels = (uint32_t)VBE->w * (uint32_t)VBE->h;
	
	uint8_t red = (color >> 16) & 0xFF;
	uint8_t green = (color >> 8) & 0xFF;
	uint8_t blue = color & 0xFF;

    	for (uint32_t i = 0; i < total_pixels * 3; i += 3) {
        	fb[i]     = blue; // Blue
        	fb[i + 1] = green; // Green
        	fb[i + 2] = red; // Red
    	}
}

void draw_char_at(char c, uint32_t x, uint32_t y, uint32_t color)
{
	volatile uint8_t* fb = (volatile uint8_t*)VBE->fb_phys_addr;
	uint16_t pitch = (uint16_t)VBE->p;

	uint8_t red = (color >> 16) & 0xFF;
    	uint8_t green = (color >> 8) & 0xFF;
    	uint8_t blue = color & 0xFF;
	
	uint8_t char_index = (uint8_t)c - 32;

    	const uint8_t* char_glyph = font[char_index];

	for (int row = 0; row < 8; row++) {
        	uint8_t row_bits = char_glyph[row];
        	for (int col = 0; col < 8; col++) {
            		if (row_bits & (1 << (7 - col))) {
                		uint32_t pixel_index = ((y + row) * pitch) + ((x + col) * 3);
                		fb[pixel_index]     = blue;
                		fb[pixel_index + 1] = green;
                		fb[pixel_index + 2] = red;
            		}
        	}
    	}
}

void draw_char(char c, uint32_t color){
	switch (c){
		case '\b':{
			break;
		}
		case '\n':{
			/*
			cursor_busy = 1;
			if (cursor_visible) toggle_cursor(cursor_x, cursor_y);
			cursor_y += 8;
			cursor_x = 0;
			if (cursor_visible) toggle_cursor(cursor_x, cursor_y);
			cursor_busy = 0;
			*/
			uint32_t horiz = (cursor_bounds.min_x - cursor_x) / 8;
			move_cursor(horiz, 1);
			break;
		}
		case '\t':{
			break;
			  }
		default: {
			cursor_busy = 1;
			if (cursor_visible) toggle_cursor(cursor_x, cursor_y);
			draw_char_at(c, cursor_x, cursor_y, color);
			cursor_x += 8;
			if (cursor_visible) toggle_cursor(cursor_x, cursor_y);
			cursor_busy = 0;
			break;
		}
	}
}

void print_string_at(const char* str, uint32_t startx, uint32_t starty, uint32_t color)
{
	int x = startx;
	while(*str){
		draw_char_at(*str, x, starty, color);
		str++;
		x+=8;	
	}
}

void print_string(const char* str, uint32_t color){
	while(*str){
		draw_char(*str, color);
		str++;
	}
}

void print_hex(uint32_t val, int start_x, int y)
{
	char hex_chars[] = "0123456789ABCDEF";
	char buf[8];
	for (int i = 7; i > 0; i--){
		buf[i] = hex_chars[val & 0xF];
		val >>= 4;
	}
	draw_char_at('0', start_x, y, 0x0000FF00);
	draw_char_at('x', start_x + 8, y, 0x0000FF00);
	int x = start_x + 8;
	for (int i = 0; i < 8; i++){
		draw_char_at(buf[i], x, y, 0x0000FF00);
		x+=8;
	}
}

void draw_block(uint32_t x, uint32_t y, uint32_t color)
{
	volatile uint8_t* fb = (volatile uint8_t*)VBE->fb_phys_addr;
	uint16_t pitch = (uint16_t)VBE->p;

    	uint8_t blue  = color & 0xFF;
    	uint8_t green = (color >> 8) & 0xFF;
        uint8_t red   = (color >> 16) & 0xFF;

    	// Force draw a solid 8x8 block instead of looking up font bits
    	for (int row = 0; row < 8; row++) {
        	for (int col = 0; col < 8; col++) {
            		uint32_t pixel_index = ((y + row) * pitch) + ((x + col) * 3);
            		fb[pixel_index]     = blue;
            		fb[pixel_index + 1] = green;
            		fb[pixel_index + 2] = red;
       		 }
    	}
}

void toggle_cursor(uint32_t x, uint32_t y)
{
	volatile uint8_t* fb = (volatile uint8_t*)VBE->fb_phys_addr;
	uint16_t p  = VBE->p;
	for (int r = 0; r < 8; r++){
		for (int c = 0; c < 8; c++){
			uint32_t pi = ((y + r)*p) + ((x + c)*3);
			fb[pi] ^= 0xFF;
			fb[pi + 1] ^= 0xFF;
			fb[pi + 2] ^= 0xFF;
		}
	}
}

void move_cursor(int horizontal, int vertical){	
	cursor_busy = 1;
	int cursor_x_next = cursor_x + (horizontal * 8);
	int cursor_y_next = cursor_y + (vertical * 8);
	
	if (cursor_x_next < cursor_bounds.min_x || cursor_x_next >= cursor_bounds.max_x ||
		       	cursor_y_next < cursor_bounds.min_y || cursor_y_next >=cursor_bounds.max_y){
		return;
	}

	if (cursor_visible){
		toggle_cursor(cursor_x, cursor_y);
	}
	
	cursor_x += (horizontal * 8);
	cursor_y += (vertical * 8);

	if (cursor_visible){
		toggle_cursor(cursor_x, cursor_y);
	}
	cursor_busy = 0;
}

