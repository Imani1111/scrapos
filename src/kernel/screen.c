void cursor_blink(){
	if (cursor_busy) return;
	cursor_blink_monitor++;
	if (cursor_blink_monitor % 16 == 0){
		if (cursor_visible){
			toggle_cursor(cursor_x, cursor_y);
			cursor_visible = 0;
		}else{
			toggle_cursor(cursor_x, cursor_y);
			cursor_visible = 1;
		}
	}
}

void draw_pixel(uint32_t x, uint32_t y, uint32_t color){
	volatile uint8_t* fb = (volatile uint8_t*)VBE->fb_phys_addr;
	uint16_t pitch = (uint16_t)VBE->p;
	uint32_t pixel_index = (y * pitch) + (x * 3);
	uint8_t red = (color >> 16) & 0xFF;
	uint8_t green = (color >> 8) & 0xFF;
	uint8_t blue = color & 0xFF;

	fb[pixel_index] = blue;
	fb[pixel_index + 1] = green;
	fb[pixel_index + 2] = red;
}

