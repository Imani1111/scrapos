{
	cursor_bounds.min_x = c->min_x;
	cursor_bounds.max_x = c->max_x;
	cursor_bounds.min_y = c->min_y;
	cursor_bounds.max_y = c->max_y;
	set_cursor(cpos->cx, cpos->cy);
}
